def build_html(chapters):
    import json, re
    data = []
    for c in chapters:
        for idx, e in enumerate(c["entries"], 1):
            evv = e["ev"].replace("证据等级：", "").strip()
            src_raw = _strip(e["src"], "来源：")
            urls = re.findall(r"https?://\S+", src_raw)
            url = urls[-1] if urls else ""
            note_raw = _strip(e["note"], "备注：") if e["note"] else ""
            data.append({
                "ch": c["no"], "ch_title": c["title"],
                "no": idx, "title": e["title"], "tags": e["tags"],
                "cost": _strip(e["cost"], "成本："),
                "plain": _strip(e["plain"], "说人话："),
                "gain": _strip(e["gain"], "收益："),
                "ev": evv, "src": src_raw, "url": url, "note": note_raw,
            })
    meta = {"chapters": [{"no": c["no"], "title": c["title"]} for c in chapters]}
    data_json = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    meta_json = json.dumps(meta, ensure_ascii=False).replace("</", "<\\/")
    html = HTML_HEAD + "<script>var DATA=" + data_json + ";var META=" + meta_json + ";</script>" + HTML_BODY
    return html

