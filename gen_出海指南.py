def _dest_sections(chapters):
    import re as _re
    data = _flatten(chapters)
    for e in data:
        src_clean = _re.sub(r"https?://\S+", "", e["src"])
        e["_hay"] = (e["title"] + e["plain"] + e["gain"] + src_clean + e["tags"] + e["ch_title"]).lower()
    sections = []
    for d in DEST_SPECS:
        # 负向后行断言：ASCII 关键词只在不被字母/数字紧跟时才算命中，
        # 避免 "IRS" 误中 "Home Affairs"、URL 子串等。
        pats = [r"(?<![a-z0-9])" + _re.escape(k.lower()) for k in d["kw"]]
        matches = [e for e in data if any(_re.search(p, e["_hay"]) for p in pats)]
        matches.sort(key=lambda e: (e["ch"], e["no"]))
        sections.append(dict(d, entries=matches))
    return sections

