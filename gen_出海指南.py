def slug(title):
    import re
    s = title.strip().lower().replace(" ", "-")
    # GitHub anchor 规则：小写，空格转连字符，其余非字母/数字/中文/连字符的字符直接删除（不折叠连字符）
    s = re.sub(r"[^0-9a-z\u4e00-\u9fff\-]", "", s)
    return s

def _strip(s, pre):
    s = (s or "").strip()
    return s[len(pre):] if s.startswith(pre) else s

